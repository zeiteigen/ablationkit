/**
 * Generates, from the TypeBox schemas in src/ (ADR 0005):
 *   - packages/protocol/schemas/<file>.schema.json   (JSON Schema 2020-12, the machine-readable contract)
 *   - python/ablationkit-protocol/src/ablationkit_protocol/models.py   (Pydantic v2 models)
 *   - docs/api/protocol.md   (reference tables)
 *
 * `--check` regenerates in memory and fails if any committed file differs (CI drift check).
 * Only a deliberate JSON Schema subset is supported; anything else is a generator error, so
 * TypeScript and Python can never silently disagree about what a schema means.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { SCHEMAS, type SchemaEntry } from "../src/index.ts";

const ROOT = resolve(import.meta.dir, "../../..");
const SCHEMA_DIR = join(ROOT, "packages/protocol/schemas");
const PY_MODELS = join(ROOT, "python/ablationkit-protocol/src/ablationkit_protocol/models.py");
const DOC = join(ROOT, "docs/api/protocol.md");
const HEADER =
  "Generated by packages/protocol/scripts/generate.ts from packages/protocol/src. Do not edit.";

/** TypeBox's encoding of Record<string, X>. */
const RECORD_KEY = "^(.*)$";

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };
type Schema = { [k: string]: Json };

const ALLOWED_KEYS = new Set([
  "title",
  "description",
  "type",
  "const",
  "pattern",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "items",
  "minItems",
  "maxItems",
  "properties",
  "required",
  "additionalProperties",
  "patternProperties",
  "anyOf",
]);

class GeneratorError extends Error {}

function fail(path: string, msg: string): never {
  throw new GeneratorError(`${path}: ${msg}`);
}

/** Strip TypeBox symbols and check the schema stays inside the supported subset. */
function toPlain(schema: unknown, path: string): Schema {
  const plain = JSON.parse(JSON.stringify(schema)) as Schema;
  check(plain, path);
  return plain;
}

function check(s: Schema, path: string): void {
  for (const key of Object.keys(s)) {
    if (!ALLOWED_KEYS.has(key)) fail(path, `unsupported JSON Schema keyword "${key}"`);
  }
  if (s["type"] === "null") fail(path, "null is not allowed in protocol schemas; omit the field");
  const pattern = s["pattern"];
  if (typeof pattern === "string") {
    if (!pattern.startsWith("^") || !pattern.endsWith("$")) fail(path, "patterns must be anchored");
    if (/\\[dDwWsSbB]|\(\?/.test(pattern)) {
      fail(
        path,
        "patterns must avoid \\d, \\w, \\s, \\b and groups with (?…): they differ across engines",
      );
    }
  }
  if (s["type"] === "number" && !("const" in s)) {
    fail(path, "use Type.Integer; float parity is not yet specified");
  }
  const props = s["properties"];
  if (props && typeof props === "object" && !Array.isArray(props)) {
    for (const [k, v] of Object.entries(props)) {
      if (!/^[a-z][a-z0-9_]*$/.test(k)) fail(`${path}.${k}`, "field names must be snake_case");
      check(v as Schema, `${path}.${k}`);
    }
    if (s["additionalProperties"] !== false)
      fail(path, "objects must set additionalProperties: false");
  }
  const pp = s["patternProperties"];
  if (pp && typeof pp === "object" && !Array.isArray(pp)) {
    const keys = Object.keys(pp);
    if (keys.length !== 1 || keys[0] !== RECORD_KEY)
      fail(path, "only Record<string, X> is supported");
    check((pp as Schema)[RECORD_KEY] as Schema, `${path}[*]`);
  }
  if (s["items"]) check(s["items"] as Schema, `${path}[]`);
  if (Array.isArray(s["anyOf"])) {
    for (const [i, m] of s["anyOf"].entries()) check(m as Schema, `${path}|${i}`);
  }
}

// ---------------------------------------------------------------- Python

function pyLiteral(v: Json): string {
  if (typeof v === "boolean") return v ? "True" : "False";
  if (typeof v === "number" || typeof v === "string") return JSON.stringify(v);
  throw new GeneratorError(`unsupported const ${JSON.stringify(v)}`);
}

class PythonEmitter {
  private readonly aliases = new Map<string, string>();
  private readonly models = new Map<string, string>();
  private usesJsonValue = false;
  private usesField = false;
  private usesStringConstraints = false;
  private usesLiteral = false;
  private usesAnnotated = false;
  private usesRejectBool = false;

  type(s: Schema, path: string, topLevel = false): string {
    const title = typeof s["title"] === "string" ? s["title"] : undefined;
    if (s["type"] === "object" && s["properties"]) {
      const name = title ?? fail(path, "nested objects need a title to name the Python model");
      if (!this.models.has(name)) this.models.set(name, this.model(name, s, path));
      return name;
    }
    const inner = this.inline(s, path);
    if (title && !topLevel) {
      const existing = this.aliases.get(title);
      const def = `${title} = ${inner}`;
      if (existing !== undefined && existing !== def)
        fail(path, `two different types titled ${title}`);
      this.aliases.set(title, def);
      return title;
    }
    return inner;
  }

  private inline(s: Schema, path: string): string {
    if ("const" in s) {
      this.usesLiteral = true;
      const lit = `Literal[${pyLiteral(s["const"] as Json)}]`;
      if (typeof s["const"] !== "number") return lit;
      // Python's Literal[1] accepts True (True == 1); TypeScript does not.
      this.usesAnnotated = true;
      this.usesRejectBool = true;
      return `Annotated[${lit}, BeforeValidator(reject_bool)]`;
    }
    if (Array.isArray(s["anyOf"])) {
      const members = s["anyOf"] as Schema[];
      if (members.every((m) => "const" in m)) {
        this.usesLiteral = true;
        if (members.some((m) => typeof m["const"] === "number")) {
          fail(path, "numeric literal unions are not supported (bool parity)");
        }
        return `Literal[${members.map((m) => pyLiteral(m["const"] as Json)).join(", ")}]`;
      }
      return members.map((m, i) => this.type(m, `${path}|${i}`)).join(" | ");
    }
    switch (s["type"]) {
      case "string": {
        const args: string[] = [];
        if (typeof s["pattern"] === "string") args.push(`pattern=${JSON.stringify(s["pattern"])}`);
        if (typeof s["minLength"] === "number") args.push(`min_length=${s["minLength"]}`);
        if (typeof s["maxLength"] === "number") args.push(`max_length=${s["maxLength"]}`);
        if (args.length === 0) return "str";
        this.usesStringConstraints = true;
        this.usesAnnotated = true;
        return `Annotated[str, StringConstraints(${args.join(", ")})]`;
      }
      case "integer": {
        const args: string[] = [];
        if (typeof s["minimum"] === "number") args.push(`ge=${s["minimum"]}`);
        if (typeof s["maximum"] === "number") args.push(`le=${s["maximum"]}`);
        if (args.length === 0) return "int";
        this.usesField = true;
        this.usesAnnotated = true;
        return `Annotated[int, Field(${args.join(", ")})]`;
      }
      case "boolean":
        return "bool";
      case "array": {
        const item = this.type(s["items"] as Schema, `${path}[]`);
        const args: string[] = [];
        if (typeof s["minItems"] === "number") args.push(`min_length=${s["minItems"]}`);
        if (typeof s["maxItems"] === "number") args.push(`max_length=${s["maxItems"]}`);
        if (args.length === 0) return `list[${item}]`;
        this.usesField = true;
        this.usesAnnotated = true;
        return `Annotated[list[${item}], Field(${args.join(", ")})]`;
      }
      case "object": {
        const pp = s["patternProperties"] as Schema | undefined;
        const value = pp?.[RECORD_KEY] as Schema | undefined;
        if (!value) fail(path, "object without properties must be a Record");
        return `dict[str, ${this.type(value, `${path}[*]`)}]`;
      }
      case undefined:
        if (Object.keys(s).every((k) => k === "description" || k === "title")) {
          this.usesJsonValue = true;
          return "JsonValue";
        }
        return fail(path, "schema without a type");
      default:
        return fail(path, `unsupported type ${JSON.stringify(s["type"])}`);
    }
  }

  private model(name: string, s: Schema, path: string): string {
    const required = new Set((s["required"] as string[] | undefined) ?? []);
    const lines = [`class ${name}(ProtocolModel):`];
    if (typeof s["description"] === "string") lines.push(`    ${pyDocstring(s["description"])}`);
    lines.push("");
    for (const [field, raw] of Object.entries(s["properties"] as Record<string, Schema>)) {
      const t = this.type(raw, `${path}.${field}`);
      const desc = typeof raw["description"] === "string" ? raw["description"] : undefined;
      const optional = !required.has(field);
      const fieldArgs: string[] = [];
      if (optional) fieldArgs.push("default=None");
      if (desc) fieldArgs.push(`description=${JSON.stringify(desc)}`);
      if (fieldArgs.length) this.usesField = true;
      const annotation = optional ? `${t} | None` : t;
      lines.push(
        fieldArgs.length
          ? `    ${field}: ${annotation} = Field(${fieldArgs.join(", ")})`
          : `    ${field}: ${annotation}`,
      );
    }
    return lines.join("\n");
  }

  render(entries: readonly SchemaEntry[], plain: Map<string, Schema>): string {
    for (const e of entries) this.type(plain.get(e.name) as Schema, e.name, true);
    const typing = [
      ...(this.usesAnnotated ? ["Annotated"] : []),
      ...(this.usesLiteral ? ["Literal"] : []),
    ];
    const pyd = [
      ...(this.usesRejectBool ? ["BeforeValidator"] : []),
      ...(this.usesField ? ["Field"] : []),
      ...(this.usesJsonValue ? ["JsonValue"] : []),
      ...(this.usesStringConstraints ? ["StringConstraints"] : []),
    ];
    const out = [
      `"""${HEADER}"""`,
      "",
      "from __future__ import annotations",
      "",
      ...(typing.length ? [`from typing import ${typing.join(", ")}`, ""] : []),
      `from pydantic import ${pyd.join(", ")}`,
      "",
      `from ablationkit_protocol._base import ProtocolModel${this.usesRejectBool ? ", reject_bool" : ""}`,
      "",
      ...[...this.aliases.values()],
      "",
      "",
      [...this.models.values()].join("\n\n\n"),
      "",
      "",
      "MODELS: dict[str, type[ProtocolModel]] = {",
      ...entries.map((e) => `    ${JSON.stringify(e.name)}: ${e.name},`),
      "}",
      '"""Top-level protocol models by schema name."""',
      "",
      "SCHEMA_VERSIONS: dict[str, int] = {",
      ...entries.map((e) => `    ${JSON.stringify(e.name)}: ${e.version},`),
      "}",
      '"""Current schema_version of each top-level schema."""',
      "",
      "__all__ = [",
      ...[...this.aliases.keys(), ...this.models.keys(), "MODELS", "SCHEMA_VERSIONS"]
        .sort()
        .map((n) => `    ${JSON.stringify(n)},`),
      "]",
      "",
    ];
    return out.join("\n");
  }
}

function pyDocstring(text: string): string {
  return `"""${text.replaceAll("\\", "\\\\").replaceAll('"""', '\\"\\"\\"')}"""`;
}

/** Normalize generated Python with the repo's own ruff config (lint fixes, then format). */
function ruffNormalize(source: string, path: string): string {
  const name = relative(ROOT, path);
  let text = source;
  for (const args of [
    ["check", "--fix", "--quiet", "--stdin-filename", name, "-"],
    ["format", "--stdin-filename", name, "-"],
  ]) {
    const proc = Bun.spawnSync(["uv", "run", "--frozen", "ruff", ...args], {
      cwd: ROOT,
      stdin: new TextEncoder().encode(text),
      stdout: "pipe",
      stderr: "pipe",
    });
    if (proc.exitCode !== 0) {
      throw new GeneratorError(
        `ruff ${args[0]} failed on generated ${name}:\n${proc.stdout}${proc.stderr}`,
      );
    }
    text = proc.stdout.toString();
  }
  return text;
}

// ---------------------------------------------------------------- Docs

function docType(s: Schema): string {
  if (typeof s["title"] === "string" && !s["properties"]) return `\`${s["title"]}\``;
  if ("const" in s) return `\`${JSON.stringify(s["const"])}\``;
  if (s["type"] === "object") return "object";
  if (s["type"] === "array") return `array of ${docType(s["items"] as Schema)}`;
  return typeof s["type"] === "string" ? s["type"] : "any JSON";
}

function renderDoc(entries: readonly SchemaEntry[], plain: Map<string, Schema>): string {
  const lines = [
    "# Protocol schemas",
    "",
    `<!-- ${HEADER} Run \`bun run protocol:generate\`. -->`,
    "",
    "Versioned contracts shared by TypeScript (`@ablationkit/protocol`) and Python (`ablationkit-protocol`).",
    "Machine-readable JSON Schemas are in [`packages/protocol/schemas/`](../../packages/protocol/schemas/).",
    "Conventions and the generation pipeline: ADR 0005.",
    "",
  ];
  const scalars = new Map<string, Schema>();
  for (const e of entries) {
    const s = plain.get(e.name) as Schema;
    lines.push(`## ${e.name} (v${e.version})`, "", String(s["description"] ?? ""), "");
    lines.push(
      `Schema: [\`${e.file}.schema.json\`](../../packages/protocol/schemas/${e.file}.schema.json)`,
      "",
    );
    lines.push("| Field | Type | Required | Description |", "| --- | --- | --- | --- |");
    const required = new Set((s["required"] as string[] | undefined) ?? []);
    for (const [field, raw] of Object.entries(s["properties"] as Record<string, Schema>)) {
      if (typeof raw["title"] === "string") scalars.set(raw["title"], raw);
      const desc = String(raw["description"] ?? "").replaceAll("|", "\\|");
      lines.push(
        `| \`${field}\` | ${docType(raw)} | ${required.has(field) ? "yes" : "no"} | ${desc} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    "## Shared types",
    "",
    "| Type | Base | Constraint | Description |",
    "| --- | --- | --- | --- |",
  );
  for (const [name, s] of [...scalars].sort(([a], [b]) => a.localeCompare(b))) {
    const c =
      typeof s["pattern"] === "string"
        ? `\`${s["pattern"].replaceAll("|", "\\|")}\``
        : s["type"] === "integer"
          ? `${s["minimum"] ?? "-∞"} … ${s["maximum"] ?? "∞"}`
          : "";
    lines.push(
      `| \`${name}\` | ${s["type"]} | ${c} | ${String(s["description"] ?? "").replaceAll("|", "\\|")} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

// ---------------------------------------------------------------- Main

export function generate(): Map<string, string> {
  const files = new Map<string, string>();
  const plain = new Map<string, Schema>();
  for (const e of SCHEMAS) {
    const s = toPlain(e.schema, e.name);
    const props = s["properties"] as Record<string, Schema> | undefined;
    if (props?.["schema_version"]?.["const"] !== e.version) {
      fail(e.name, `schema_version const must equal the registered version ${e.version}`);
    }
    plain.set(e.name, s);
    const doc = {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      $id: `urn:ablationkit:schema:${e.file}`,
      ...s,
    };
    files.set(join(SCHEMA_DIR, `${e.file}.schema.json`), `${JSON.stringify(doc, null, 2)}\n`);
  }
  files.set(PY_MODELS, ruffNormalize(new PythonEmitter().render(SCHEMAS, plain), PY_MODELS));
  files.set(DOC, renderDoc(SCHEMAS, plain));
  return files;
}

if (import.meta.main) {
  const checkOnly = process.argv.includes("--check");
  const files = generate();
  const drifted: string[] = [];
  for (const [path, content] of files) {
    let current: string | undefined;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = undefined;
    }
    if (current === content) continue;
    drifted.push(relative(ROOT, path));
    if (!checkOnly) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  if (checkOnly && drifted.length > 0) {
    console.error(
      `protocol: generated files are stale:\n  ${drifted.join("\n  ")}\nRun: bun run protocol:generate`,
    );
    process.exit(1);
  }
  console.log(
    checkOnly
      ? `protocol: ${files.size} generated files up to date`
      : `protocol: wrote ${drifted.length} of ${files.size} generated files`,
  );
}
