/**
 * `ablationkit coordinator start|stop|status`. By default the coordinator runs as the systemd
 * user service `ablationkit-coordinator.service` (ADR 0009); `--foreground` runs it in this
 * process instead (development, or machines without a user systemd).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import {
  activeBuild,
  CoordinatorLockedError,
  CoordinatorMovedError,
  moveCoordinator,
  RestoreError,
  readLockPid,
  runCoordinator,
  runtimePaths,
} from "@ablationkit/server";
import { type SocketHealth, socketHealth } from "../client.ts";
import { type CliContext, flag, parseArgs, printJson, UsageError } from "../context.ts";

const DEFAULT_UNIT = "ablationkit-coordinator.service";

function unitName(env: CliContext["env"]): string {
  const n = env["ABLATIONKIT_SERVICE"];
  if (n === undefined || n === "") return DEFAULT_UNIT;
  if (!/^[A-Za-z0-9_.@-]+\.service$/.test(n))
    throw new UsageError(`ABLATIONKIT_SERVICE must be a unit name ending in .service`);
  return n;
}

function unitDir(env: CliContext["env"]): string {
  return join(env["XDG_CONFIG_HOME"] || join(homedir(), ".config"), "systemd", "user");
}

/** The `ABLATIONKIT_HOME` a rendered unit runs with (undefined if it has none). */
export function unitHome(unit: string): string | undefined {
  const m = /^Environment="ABLATIONKIT_HOME=((?:[^"\\]|\\.)*)"$/m.exec(unit);
  return m?.[1]?.replace(/\\(.)/g, "$1").replace(/%%/g, "%");
}

/** systemd quoting for ExecStart/Environment values. */
function q(v: string): string {
  return `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%")}"`;
}

/** Where `coordinator start` runs from: the active modified build, or this install. */
export function serverRoot(home: string, repoRoot: string): { root: string; build_id?: string } {
  const a = activeBuild(home);
  return a ? { root: a.record.source_dir, build_id: a.record.build_id } : { root: repoRoot };
}

export function renderUnit(opts: {
  bun: string;
  serverMain: string;
  home: string;
  workingDirectory: string;
  /** Absolute path of `uv`, which the MLflow sidecar needs (the unit has no login PATH). */
  uv?: string | undefined;
  /** Boot with every extension inactive; the next plain `start` regenerates the unit without it. */
  safeMode?: boolean;
}): string {
  return `# Generated by \`ablationkit coordinator start\`. Regenerated on every start; do not edit.
[Unit]
Description=AblationKit coordinator
After=default.target

[Service]
Type=simple
ExecStart=${q(opts.bun)} ${q(opts.serverMain)}
WorkingDirectory=${opts.workingDirectory.replace(/%/g, "%%")}
Environment=${q(`ABLATIONKIT_HOME=${opts.home}`)}
${opts.uv ? `Environment=${q(`ABLATIONKIT_UV=${opts.uv}`)}\n` : ""}${opts.safeMode ? `Environment=${q("ABLATIONKIT_SAFE_MODE=1")}\n` : ""}Restart=on-failure
RestartSec=2
# Exit code 3 means another coordinator holds the runtime lock; do not restart-loop on it.
RestartPreventExitStatus=3
UMask=0077

[Install]
WantedBy=default.target
`;
}

function systemctl(args: string[]): { code: number; out: string } {
  try {
    const p = Bun.spawnSync(["systemctl", "--user", ...args], { stdout: "pipe", stderr: "pipe" });
    return { code: p.exitCode ?? -1, out: `${p.stdout.toString()}${p.stderr.toString()}`.trim() };
  } catch (e) {
    return { code: -1, out: (e as Error).message };
  }
}

async function waitForHealth(home: string, timeoutMs: number): Promise<SocketHealth | undefined> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const h = await socketHealth(home);
    if (h) return h;
    await Bun.sleep(100);
  }
  return undefined;
}

export async function coordinatorCommand(
  argv: readonly string[],
  ctx: CliContext,
): Promise<number> {
  const [sub, ...rest] = argv;
  const args = parseArgs(rest, ["json", "foreground", "safe-mode"]);
  const safeMode = args.flags["safe-mode"] === true;
  const asJson = args.flags["json"] === true;
  const unit = unitName(ctx.env);

  if (sub === "status") {
    const h = await socketHealth(ctx.home);
    const active = systemctl(["is-active", unit]).out || "unknown";
    if (asJson)
      printJson(ctx, { running: h !== undefined, service: { unit, state: active }, ...(h ?? {}) });
    else if (h)
      ctx.out(
        `running (pid ${h.pid}, since ${h.started_at})\n  human  ${h.urls.human}\n  agent  ${h.urls.agent}\n  worker ${h.urls.worker}\n  service ${unit}: ${active}\n`,
      );
    else ctx.out(`not running (service ${unit}: ${active})\n`);
    return h ? 0 : 1;
  }

  if (sub === "restart") {
    const stopped = await coordinatorCommand(["stop"], { ...ctx, out: () => {} });
    if (stopped !== 0) return stopped;
    const deadline = Date.now() + 30_000;
    while ((await socketHealth(ctx.home)) && Date.now() < deadline) await Bun.sleep(100);
    return coordinatorCommand(["start", ...rest], ctx);
  }

  if (sub === "move") {
    const out = flag(args, "out");
    if (!out) throw new UsageError("usage: ablationkit coordinator move --out FILE.tar.gz");
    if (await socketHealth(ctx.home))
      throw new UsageError(
        "the coordinator is running; stop it first (ablationkit coordinator stop) so nothing changes after the backup",
      );
    let r: Awaited<ReturnType<typeof moveCoordinator>>;
    try {
      r = await moveCoordinator({ home: ctx.home, out });
    } catch (e) {
      if (
        e instanceof CoordinatorLockedError ||
        e instanceof CoordinatorMovedError ||
        e instanceof RestoreError
      )
        throw new UsageError(e.message);
      throw e;
    }
    if (asJson) printJson(ctx, r);
    else
      ctx.out(
        `backup ${r.marker.backup_id} packed into ${r.marker.archive} (${r.bytes} bytes, sha256 ${r.marker.archive_sha256})\n` +
          `this home is now retired: the coordinator refuses to start here (${ctx.home}/moved.json)\n` +
          `on the new machine:\n  ablationkit backup restore ${r.marker.archive} [--project ID=PATH]... [--worker-url URL]\n  ablationkit coordinator start\n`,
      );
    return 0;
  }

  if (sub === "start") {
    if (args.flags["foreground"] === true) return runCoordinator(ctx.home, { safeMode });
    const already = await socketHealth(ctx.home);
    if (already) {
      if (asJson) printJson(ctx, { started: false, running: true, ...already });
      else
        ctx.out(
          `already running (pid ${already.pid}) at ${already.urls.human}${safeMode ? "\n  to boot in safe mode: ablationkit coordinator restart --safe-mode" : ""}\n`,
        );
      return 0;
    }
    const dir = unitDir(ctx.env);
    const path = join(dir, unit);
    // An activated modified build (ADR 0022 § Level 2) runs instead of this install.
    const root = serverRoot(ctx.home, ctx.repoRoot);
    if (root.build_id && !asJson)
      ctx.out(`starting modified build ${root.build_id} (${root.root})\n`);
    const content = renderUnit({
      bun: process.execPath,
      serverMain: resolve(root.root, "apps/server/src/main.ts"),
      home: ctx.home,
      workingDirectory: root.root,
      uv: ctx.env["ABLATIONKIT_UV"] ?? Bun.which("uv") ?? undefined,
      safeMode,
    });
    // One unit serves one runtime home. Never repoint an existing unit at another home: that would
    // silently switch the researcher's coordinator to a different data directory on its next start.
    const existingHome = existsSync(path) ? unitHome(readFileSync(path, "utf8")) : undefined;
    if (existingHome !== undefined && existingHome !== ctx.home) {
      ctx.err(
        `${unit} already runs the coordinator for ABLATIONKIT_HOME=${existingHome}, not ${ctx.home}.\n` +
          `To run a second coordinator, set ABLATIONKIT_SERVICE=<another-name>.service (and give it its own ports in settings.json), or use \`ablationkit coordinator start --foreground\`.\n`,
      );
      return 1;
    }
    mkdirSync(dir, { recursive: true });
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) writeFileSync(path, content);
    for (const step of [["daemon-reload"], ["start", unit]]) {
      const r = systemctl(step);
      if (r.code !== 0) {
        ctx.err(
          `systemctl --user ${step.join(" ")} failed: ${r.out}\nWithout a user systemd, run \`ablationkit coordinator start --foreground\`.\n`,
        );
        return 1;
      }
    }
    const h = await waitForHealth(ctx.home, 15_000);
    if (!h) {
      ctx.err(
        `the service started but the coordinator did not answer; see \`journalctl --user -u ${unit}\`\n`,
      );
      return 1;
    }
    if (asJson) printJson(ctx, { started: true, running: true, service: { unit, path }, ...h });
    else
      ctx.out(
        `started ${unit} (pid ${h.pid})${safeMode ? " in SAFE MODE: every extension is inactive" : ""}\n  human  ${h.urls.human}\n  next: \`ablationkit ui\` or \`ablationkit login\`\n`,
      );
    return 0;
  }

  if (sub === "stop") {
    // Only stop the service if it runs this home; another home's coordinator is not ours to stop.
    const unitPath = join(unitDir(ctx.env), unit);
    const servedHome = existsSync(unitPath) ? unitHome(readFileSync(unitPath, "utf8")) : undefined;
    const ours = servedHome === undefined || servedHome === ctx.home;
    const active = ours ? systemctl(["is-active", unit]) : { code: 1, out: "not ours" };
    if (active.out === "active" || active.out === "activating") {
      const r = systemctl(["stop", unit]);
      if (r.code !== 0) {
        ctx.err(`systemctl --user stop ${unit} failed: ${r.out}\n`);
        return 1;
      }
      ctx.out(`stopped ${unit}\n`);
      return 0;
    }
    // A foreground coordinator: signal the lock holder.
    const pid = readLockPid(runtimePaths(ctx.home).lock);
    if (pid !== undefined && (await socketHealth(ctx.home))?.pid === pid) {
      process.kill(pid, "SIGTERM");
      ctx.out(`sent SIGTERM to coordinator pid ${pid}\n`);
      return 0;
    }
    ctx.out("not running\n");
    return 0;
  }

  throw new UsageError(
    "usage: ablationkit coordinator start [--foreground] [--safe-mode] | restart [--safe-mode] | stop | status [--json]\n       ablationkit coordinator move --out FILE.tar.gz   (stopped coordinator: back up, pack, retire this home)",
  );
}
