/**
 * The security threat map doc. Data: scripts/security-threats.ts.
 *
 *   bun scripts/security-map.ts --write     regenerate docs/security/threat-map.md
 *   bun scripts/security-map.ts --check     fail if the doc or a named test is out of date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { AREAS, OUT_OF_SCOPE, type Proof } from "./security-threats.ts";

export const ROOT = resolve(import.meta.dir, "..");
export const DOC = "docs/security/threat-map.md";

const LEVELS: Record<string, string> = {
  enforced:
    "A mechanism outside the adversary's control blocks it: the browser, or the coordinator against a party with no access to the workstation.",
  "server-side": "The Git host enforces it.",
  "approval-gated": "A person decides each time.",
  authoritative:
    "Authoritative for everything AblationKit itself executes; advisory against a misbehaving agent that goes around AblationKit (spec §7.11).",
  advisory:
    "AblationKit's gates and the agent's instructions. A misbehaving agent could bypass it.",
};

const cell = (s: string) => s.replaceAll("|", "\\|");

function proofLine(p: Proof): string {
  const suite = p.suite === "unit" ? "" : ` (\`${p.suite}\`)`;
  const file = p.file.split("/").at(-1);
  return `\`${file}\`: ${cell(p.test)}${suite}`;
}

export function render(): string {
  const L: string[] = [
    "# Security threat map",
    "",
    "<!-- Generated by `bun run security:map` from scripts/security-threats.ts. Do not edit. -->",
    "",
    "Each threat, the control that answers it, how far that control can be trusted, and the tests that prove it. A test is listed by its title, and a check fails if it disappears. The trust model behind the labels is [spec §7.11](../spec/AblationKit_SPEC.md); ADR 0027 records how this map is kept.",
    "",
    "Tests marked with a script name need that script (`bun run test:web`, `bun run test:desktop`); the others run in `bun run test`.",
    "",
    "## Levels",
    "",
    "| Level | Meaning |",
    "| --- | --- |",
    ...Object.entries(LEVELS).map(([k, v]) => `| ${k} | ${v} |`),
    "",
  ];
  for (const a of AREAS) {
    L.push(`## ${a.title}`, "");
    for (const t of a.threats) {
      L.push(`### ${t.id}: ${t.threat}`, "");
      L.push(`**Control:** ${t.control}. **Level:** ${t.level}.`, "");
      if (t.limit) L.push(`**Limit:** ${t.limit}`, "");
      L.push(...t.proofs.map((p) => `- ${proofLine(p)}`), "");
    }
  }
  L.push("## Out of scope for v1.0", "", ...OUT_OF_SCOPE.map((s) => `- ${s}`), "");
  return L.join("\n");
}

/** A proof whose file or test title is gone, as a message. */
export function missingProofs(): string[] {
  const out: string[] = [];
  const cache = new Map<string, string>();
  for (const a of AREAS)
    for (const t of a.threats)
      for (const p of t.proofs) {
        const abs = join(ROOT, p.file);
        if (!existsSync(abs)) {
          out.push(`${t.id}: no file ${p.file}`);
          continue;
        }
        const text = cache.get(abs) ?? readFileSync(abs, "utf8");
        cache.set(abs, text);
        if (!text.includes(p.test)) out.push(`${t.id}: no test "${p.test}" in ${p.file}`);
      }
  return out;
}

if (import.meta.main) {
  const mode = process.argv[2];
  if (mode === "--write") {
    writeFileSync(join(ROOT, DOC), render());
    console.log(`wrote ${DOC}`);
  } else if (mode === "--check") {
    const problems = missingProofs();
    if (readFileSync(join(ROOT, DOC), "utf8") !== render())
      problems.push(`${DOC} is stale: run \`bun run security:map\``);
    for (const p of problems) console.error(p);
    process.exit(problems.length ? 1 : 0);
  } else {
    console.error("usage: bun scripts/security-map.ts --write|--check");
    process.exit(2);
  }
}
